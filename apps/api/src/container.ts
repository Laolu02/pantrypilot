import { type Env } from "./config/env";
import { fileURLToPath } from "node:url";
import { systemClock, type Clock } from "./lib/clock";
import { MemoryStore } from "./store/store";
import { AuditService } from "./modules/audit/auditService";
import { InventoryService } from "./modules/inventory/inventoryService";
import { DeviceService } from "./modules/devices/deviceService";
import { PreferencesService } from "./modules/preferences/preferencesService";
import { PolicyService } from "./modules/shopping/policyService";
import { BasketService } from "./modules/shopping/basketService";
import { OrderService } from "./modules/shopping/orderService";
import { RecipeService } from "./modules/recipes/recipeService";
import { ToolRunner } from "./modules/agent/tools";
import { AgentOrchestrator } from "./modules/agent/orchestrator";
import { TemplateExplainer } from "./modules/agent/llm";
import { MockCommerceAdapter } from "./integrations/commerce/mockCommerce";
import { CommerceRegistry } from "./integrations/commerce/registry";
import { KrogerAdapter } from "./integrations/commerce/kroger";
import { WalmartAdapter } from "./integrations/commerce/walmart";
import { InstacartChannel } from "./integrations/commerce/instacart";
import { CredentialVault } from "./modules/shopping/credentialVault";
import type { FetchLike } from "./integrations/http";
import type { CommerceAdapter } from "./integrations/commerce/commerce";
import { MockPaymentAdapter } from "./integrations/payments/mockPayment";
import { PayPalPaymentAdapter } from "./integrations/payments/paypal";
import type { PaymentAdapter } from "./integrations/payments/payments";
import { SimulatorDeviceAdapter } from "./integrations/devices/simulator";
import { seedDemo } from "./modules/seed/demoData";

export async function buildContainer(env: Env, opts: { clock?: Clock; seed?: boolean; fetch?: FetchLike; sleep?: (ms: number) => Promise<void> } = {}) {
  const clock = opts.clock ?? systemClock;
  const store = new MemoryStore();
  const audit = new AuditService(store, clock);
  const commerce = new MockCommerceAdapter(clock);
  const mockPayments = new MockPaymentAdapter();
  const simulator = new SimulatorDeviceAdapter(clock, env.DEVICE_SIGNING_SECRET);
  const inventory = new InventoryService(store, clock, audit);
  const prefs = new PreferencesService(store, audit);
  const devices = new DeviceService(store, clock, audit, inventory, env.DEVICE_SIGNING_SECRET);
  const f: FetchLike = opts.fetch ?? ((u, i) => fetch(u, i));
  const credFile = env.NODE_ENV === "test" || !env.INTEGRATION_ENCRYPTION_KEY ? undefined : fileURLToPath(new URL("../.data/credentials.json", import.meta.url));
  const vault = new CredentialVault(store, clock, env.INTEGRATION_ENCRYPTION_KEY, credFile);
  let paypal: PayPalPaymentAdapter | null = null;
  if (env.PAYMENT_PROVIDER === "paypal") paypal = new PayPalPaymentAdapter({ clientId: env.PAYPAL_CLIENT_ID!, clientSecret: env.PAYPAL_CLIENT_SECRET!, ...(env.PAYPAL_BASE_URL ? { baseUrl: env.PAYPAL_BASE_URL } : {}), returnUrlBase: `${env.API_PUBLIC_URL}/api/v1/integrations/paypal/callback`, cancelUrl: `${env.API_PUBLIC_URL}/api/v1/integrations/paypal/cancel`, minimalSetup: env.PAYPAL_SETUP_MINIMAL}, { fetch: f, clock, vault, ...(opts.sleep ? { sleep: opts.sleep } : {}) });
  const payments: PaymentAdapter = paypal ?? mockPayments;
  const policies = new PolicyService(store, clock, audit, prefs, { globalKillSwitch: env.GLOBAL_PURCHASE_KILL_SWITCH, autonomyGloballyEnabled: env.AUTONOMOUS_PURCHASING_ENABLED }, payments);
  const enabled = env.COMMERCE_PROVIDERS.split(",").map((x) => x.trim()).filter(Boolean);
  const adapters: CommerceAdapter[] = [];
  let kroger: KrogerAdapter | null = null;
  if (enabled.includes("mock")) adapters.push(commerce);
  if (enabled.includes("kroger")) { kroger = new KrogerAdapter({ clientId: env.KROGER_CLIENT_ID!, clientSecret: env.KROGER_CLIENT_SECRET!, locationId: env.KROGER_LOCATION_ID!, redirectUri: env.KROGER_REDIRECT_URI! }, { fetch: f, clock, vault, ...(opts.sleep ? { sleep: opts.sleep } : {}) }); adapters.push(kroger); }
  if (enabled.includes("walmart")) adapters.push(new WalmartAdapter({ consumerId: env.WALMART_CONSUMER_ID!, keyVersion: env.WALMART_KEY_VERSION!, privateKeyPem: Buffer.from(env.WALMART_PRIVATE_KEY_B64!, "base64").toString("utf8") }, { fetch: f, clock, ...(opts.sleep ? { sleep: opts.sleep } : {}) }));
  const registry = new CommerceRegistry(adapters);
  const instacart = env.INSTACART_API_KEY ? new InstacartChannel({ apiKey: env.INSTACART_API_KEY, env: env.INSTACART_ENV }, { fetch: f, ...(opts.sleep ? { sleep: opts.sleep } : {}) }) : null;
  const baskets = new BasketService(store, clock, registry);
  const orders = new OrderService(store, clock, audit, registry, payments, policies, baskets, inventory, instacart);
  const recipes = new RecipeService(store, clock, prefs, inventory);
  const deps = { store, clock, audit, inventory, prefs, recipes, baskets, orders, policies };
  const tools = new ToolRunner(deps);
  const agent = new AgentOrchestrator({ ...deps, tools, llm: new TemplateExplainer(), devices, mock: !adapters.some((a) => a.mode === "LIVE") });
  const reset = async () => {
    await seedDemo(store, clock);
    commerce.reset();
    mockPayments.reset();
    simulator.lastEvent = null;
  };
  if (opts.seed !== false) await reset();
  return { env, clock, store, audit, inventory, devices, prefs, policies, baskets, orders, recipes, tools, agent, commerce, registry, vault, kroger, instacart, payments, mockPayments, paypal, simulator, reset };
}
export type Container = Awaited<ReturnType<typeof buildContainer>>;
